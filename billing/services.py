from datetime import date
from decimal import Decimal

from django.db.models import DecimalField, ExpressionWrapper, F, Sum, Value
from django.db.models.functions import Coalesce
from django.utils import timezone

from properties.models import Property
from .models import Bill, RatePolicy


money_field = DecimalField(max_digits=14, decimal_places=2)


def get_matching_rate_policy(property_obj, billing_year):
    return RatePolicy.get_applicable_policy(
        assembly=property_obj.assembly,
        property_use=property_obj.property_use,
        community_area=property_obj.community_area,
        building_type=property_obj.building_type,
        on_date=timezone.localdate(),
        year=billing_year,
    )


def generate_bill_for_property(property_obj, billing_year=None):
    if billing_year is None:
        billing_year = timezone.localdate().year

    if not property_obj.is_active:
        return None, False, "inactive_property"

    existing_bill = Bill.objects.filter(
        property_record=property_obj,
        billing_year=billing_year,
    ).first()

    if existing_bill:
        return existing_bill, False, "existing_bill"

    rate_policy = get_matching_rate_policy(property_obj, billing_year)
    if not rate_policy and not property_obj.is_exempt:
        return None, False, "missing_rate_policy"

    balance_expr = ExpressionWrapper(
        F("amount_due") - F("amount_paid"),
        output_field=money_field,
    )

    arrears = (
        Bill.objects.filter(property_record=property_obj)
        .exclude(status__in=["paid", "cancelled"])
        .exclude(billing_year=billing_year)
        .aggregate(
            total=Coalesce(
                Sum(balance_expr),
                Value(Decimal("0.00"), output_field=money_field),
            )
        )["total"]
    )

    bill = Bill(
        assembly=property_obj.assembly,
        property_record=property_obj,
        rate_policy=rate_policy,
        billing_year=billing_year,
        due_date=date(billing_year, 12, 31),
        rateable_value_snapshot=property_obj.rateable_value,
        rate_impost_snapshot=(rate_policy.rate_impost if rate_policy else Decimal("0.00000")),
        policy_name_snapshot=(rate_policy.policy_name if rate_policy else ""),
        property_class_snapshot=(rate_policy.property_class.name if rate_policy else ""),
        arrears_brought_forward=arrears or Decimal("0.00"),
        penalty_amount=Decimal("0.00"),
        notes="Generated by system",
    )
    bill.save()
    return bill, True, ""


def generate_missing_bills(billing_year=None, queryset=None):
    if billing_year is None:
        billing_year = timezone.localdate().year

    if queryset is None:
        queryset = Property.objects.select_related("assembly", "community_area", "property_class").filter(is_active=True)

    created_count = 0
    skipped = []

    for property_obj in queryset:
        _, created, reason = generate_bill_for_property(property_obj, billing_year=billing_year)
        if created:
            created_count += 1
        elif reason:
            skipped.append(
                {
                    "property_id": property_obj.id,
                    "property_reference": property_obj.property_reference,
                    "reason": reason,
                }
            )

    return created_count, skipped
